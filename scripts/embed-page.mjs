// Bundle the built page and the SQL migrations into the Neon Function (server/*.generated.ts, gitignored).
// Run after `npm run build`; `npm run deploy` does both.
import fs from 'node:fs'
import path from 'node:path'

const page = fs.readFileSync('dist/index.html', 'utf8')
fs.writeFileSync('server/page.generated.ts', `// Generated by scripts/embed-page.mjs from dist/index.html. Do not edit.\nexport default ${JSON.stringify(page)}\n`)
const dir = path.resolve('migrations')
const migrations = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort().map((name) => ({ name, sql: fs.readFileSync(path.join(dir, name), 'utf8') }))
fs.writeFileSync('server/migrations.generated.ts', `// Generated by scripts/embed-page.mjs from migrations/*.sql. Do not edit.\nexport default ${JSON.stringify(migrations, null, 1)}\n`)
const shark = fs.readFileSync('server/shark.html', 'utf8')
fs.writeFileSync('server/shark.generated.ts', `// Generated by scripts/embed-page.mjs from server/shark.html. Do not edit.\nexport default ${JSON.stringify(shark)}\n`)
console.log(`embedded page (${(page.length / 1024).toFixed(0)} KB) and ${migrations.length} migration(s)`)
