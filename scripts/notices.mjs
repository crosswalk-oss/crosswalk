// Third-party notices: every package in the runtime dependency tree, with its license and license text.
// The licenses used here (MIT, Apache-2.0, BSD, ISC, Zlib) ask that their notices travel with distributed copies;
// this file is how they do. Usage: npm run notices   (writes THIRD_PARTY_NOTICES.md)
//        npm run notices -- --check   (exits non-zero if the file is out of date; used by the pipeline)
import fs from 'node:fs'
import path from 'node:path'

const lock = JSON.parse(fs.readFileSync('package-lock.json', 'utf8'))
const rows = []
for (const [key, meta] of Object.entries(lock.packages)) {
  if (!key || meta.dev) continue // '' is this project; dev = build and test tools, which are not distributed
  const pj = path.join(key, 'package.json')
  if (!fs.existsSync(pj)) continue // an optional package that is not installed on this platform
  const j = JSON.parse(fs.readFileSync(pj, 'utf8'))
  const license = typeof j.license === 'object' ? j.license?.type : j.license ?? (Array.isArray(j.licenses) ? j.licenses.map((l) => l.type).join(' OR ') : 'see package')
  const repo = (typeof j.repository === 'string' ? j.repository : j.repository?.url ?? '').replace(/^git\+/, '').replace(/\.git$/, '').replace(/^git:\/\//, 'https://').replace(/^github:/, 'https://github.com/')
  const file = fs.readdirSync(key).find((f) => /^(licen[sc]e|copying)(\.|$)/i.test(f))
  const text = file ? fs.readFileSync(path.join(key, file), 'utf8').replace(/\r/g, '').trim() : ''
  rows.push({ name: j.name, version: j.version, license, repo, text, optional: !!meta.optional })
}
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))

const out = [
  '# Third-party notices',
  '',
  'Crosswalk is licensed under the Apache License 2.0 (see `LICENSE` and `NOTICE`). It is built with the open-source',
  'packages below. This file lists every package in the runtime dependency tree with its license and the license',
  'text it ships with. Build and test tools are not distributed with the application and are not listed;',
  '`npm run licenses` checks those too.',
  '',
  'Packages marked optional are companions of the PDF library that Crosswalk does not call. Some of their code is',
  'still present in the single-file build.',
  '',
  'Generated by `npm run notices` from `package-lock.json`. Do not edit by hand.',
  '',
  '| Package | Version | License | Optional |',
  '| --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.optional ? 'yes' : ''} |`),
  '',
  ...rows.flatMap((r) => [`## ${r.name} ${r.version}`, '', `License: ${r.license}${r.repo ? `  \nSource: ${r.repo}` : ''}`, '', r.text ? '```\n' + r.text + '\n```' : '_No license file is shipped in the package; the license above is from its package.json._', '']),
].join('\n')

const FILE = 'THIRD_PARTY_NOTICES.md'
if (process.argv.includes('--check')) {
  const have = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8') : ''
  if (have !== out) { console.error(`${FILE} is out of date. Run: npm run notices`); process.exit(1) }
  console.log(`${FILE} is current (${rows.length} packages).`)
} else {
  fs.writeFileSync(FILE, out)
  console.log(`wrote ${FILE}: ${rows.length} packages`)
}
